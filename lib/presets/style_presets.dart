LayerStyle _fill(int c, {int? edge, double edgeW = 0.45, double opacity = 1.0}) => LayerStyle(
      filled: true,
      outlined: edge != null,
      fill: Color(c),
      stroke: Color(edge ?? c),
      width: edgeW,
      opacity: opacity,
    );

LayerStyle _line(
  int c,
  double w, {
  double opacity = 1.0,
  double glow = 0.0,
  List<double>? dash,
  int? casing,
  double casingWidth = 0.55,
}) =>
    LayerStyle(
      filled: false,
      outlined: true,
      stroke: Color(c),
      width: w,
      opacity: opacity,
      glow: glow,
      dash: dash,
      casing: casing == null ? null : Color(casing),
      casingWidth: casingWidth,
    );

